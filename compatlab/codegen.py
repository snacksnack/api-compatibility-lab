"""Render compiled pins as a pytest module a person can read.

The generated file is the deliverable half of this phase, so it is written to
be read: one test per pin, the pin's own sentence as the docstring, the
affected workflows and the consequence above the assertion, and the assertion
itself spelled out rather than hidden behind a helper that takes the pin as an
argument. A customer handed this file can see what is being claimed about
their integration without reading this repository.

It imports `compatlab` rather than standing alone. The alternative — a
portable file that re-sends its own request prefix — would mean every
generated suite carrying its own copy of reference resolution and
canonicalization, untested, and the ticket scopes this phase to pinned tests
rather than a test framework.

Generation is deterministic: same pins and same version-A record in, same
bytes out. `compatlab pin check` regenerates and fails on any difference, so
a hand-edited assertion cannot ride along inside a generated file.
"""

from __future__ import annotations

import textwrap

from compatlab.pinning import (
    EQUALS,
    LENGTH,
    NON_EMPTY,
    PRESENT,
    REACHABLE,
    STATUS,
    PinnedTest,
)

GENERATED_PATH = "pinned/test_pinned_behavior.py"
MARKER = "GENERATED by `compatlab pin generate`"
INDENT = " " * 4
TRIPLE = '"' * 3
# The project's own line length. A generated file that does not pass the
# repository's linter is a generated file somebody will hand-edit.
WIDTH = 100


def _safe(text: str) -> str:
    """Keep a pin's own text from closing the docstring it is quoted in."""
    return text.replace(TRIPLE, "'''")


def _docstring(test: PinnedTest, version_a: str, version_b: str) -> list[str]:
    pin = test.pin
    lines = [f"{pin.assertion.replace('`', '')}."]
    who = ", ".join(pin.workflows) or "no declared workflow"
    lines.append("")
    lines.append(f"{who}: {pin.consequence}. Rule `{pin.rule}`, axis `{pin.axis}`.")
    lines.append(f"Pinned from {version_a}. On {version_b} the read at "
                 f"`{pin.locus}` returned {pin.observed_on_b or '<absent>'}.")
    lines.append(f"The client reads `{pin.declared_read}`.")
    lines.append(f"Assertion: {test.reason}.")
    if pin.caveat:
        lines.append(f"Caveat: {pin.caveat}.")
    return [_safe(line) for line in lines]


def _body(test: PinnedTest) -> list[str]:
    locus, corpus = test.pin.locus, test.pin.corpus
    if test.kind == REACHABLE:
        return [
            f'assert reached(side, "{corpus}"), \\',
            f'    "`{corpus}` did not run on this version"',
        ]
    lines = [f'response = canonical("{corpus}")']
    if test.kind == STATUS:
        lines.append(f'assert response["status"] == {test.expected!r}')
    elif test.kind == NON_EMPTY:
        lines.append(f'assert len(value_at(response, "{locus}")) > 0')
    elif test.kind == LENGTH:
        lines.append(f'assert len(value_at(response, "{locus}")) == {test.expected!r}')
    elif test.kind == PRESENT:
        lines += [
            f'value = value_at(response, "{locus}")',
            'assert value is not MISSING, "the field is gone"',
            'assert value, "the field arrived empty"',
        ]
    elif test.kind == EQUALS and (test.expected is None
                                  or isinstance(test.expected, bool)):
        # `== True` is a lint error and `assert value` would pass on any
        # truthy value, which is not what was pinned.
        lines.append(f'assert value_at(response, "{locus}") '
                     f'is {test.expected!r}')
    elif test.kind == EQUALS:
        lines.append(f'assert value_at(response, "{locus}") == {test.expected!r}')
    else:
        raise ValueError(f"no renderer for assertion kind {test.kind!r}")
    return lines


def _wrapped(line: str) -> list[str]:
    """One docstring line, folded to the project's line length."""
    if not line:
        return [""]
    if len(INDENT) + len(line) <= WIDTH:
        return [f"{INDENT}{line}"]
    # Long words do get broken, as a last resort: a response value can be one
    # unbroken 300-character run, and folding it is better than clipping it.
    # The docstring is where the reader sees what the new version returned,
    # and the assertion itself is built from the record, never from this text.
    return textwrap.wrap(line, width=WIDTH, initial_indent=INDENT,
                         subsequent_indent=INDENT, break_long_words=True,
                         break_on_hyphens=False)


def _signature(test: PinnedTest, fixture: str) -> list[str]:
    """A test name long enough to need it gets a wrapped signature."""
    one_line = f"def {test.name}({fixture}):"
    if len(one_line) <= WIDTH:
        return [one_line]
    return [f"def {test.name}(", f"{INDENT}{fixture},", "):"]


def _body_line(line: str) -> list[str]:
    """One body statement, indented, and hoisted if it would run long.

    `_wrapped` and `_signature` kept docstrings and signatures inside WIDTH
    from the start; body statements were never folded, which held only while
    every pinned locus was short. A long locus plus a long pinned value
    (`$.body.settings.payments.statement_descriptor` against
    `'WWW.NORTHWINDSUPPLY.COM'`) is the first pin to pass 100 columns, and it
    emitted a generated file the repository's own linter rejects — the exact
    thing the note on WIDTH says must not happen.

    An assertion cannot be folded the way prose can without changing what it
    asserts, so the pinned value moves to its own line instead. Nothing about
    the comparison changes; only where the literal sits.
    """
    if len(INDENT) + len(line) <= WIDTH:
        return [f"{INDENT}{line}"]
    head, sep, tail = line.rpartition(" == ")
    if sep and head.startswith("assert "):
        return [f"{INDENT}expected = {tail}", f"{INDENT}{head} == expected"]
    return [f"{INDENT}{line}"]


def render_test(test: PinnedTest, version_a: str, version_b: str) -> str:
    fixture = "side" if test.kind == REACHABLE else "canonical"
    doc = _docstring(test, version_a, version_b)
    out = _signature(test, fixture)
    if len(INDENT) + len(TRIPLE) + len(doc[0]) <= WIDTH:
        out.append(f"{INDENT}{TRIPLE}{doc[0]}")
    else:
        # A summary too long to share the opening quotes gets its own lines.
        out.append(f"{INDENT}{TRIPLE}")
        out += _wrapped(doc[0])
        out.append("")
    for line in doc[1:]:
        out += _wrapped(line)
    out.append(f"{INDENT}{TRIPLE}")
    for line in _body(test):
        out += _body_line(line)
    return "\n".join(out) + "\n"


def _imports(kinds: set[str]) -> str:
    """Only what the rendered tests use.

    An unused import in a generated file is a lint failure in a file nobody
    wrote, which is a bad way to find out that a pin changed shape.
    """
    lines = []
    if PRESENT in kinds:
        lines.append("from compatlab.findings import MISSING")
    if kinds - {REACHABLE, STATUS}:
        lines.append("from compatlab.loci import value_at")
    if REACHABLE in kinds:
        lines.append("from compatlab.pinning import reached")
    return "\n".join(lines)


def _header(tests: list[PinnedTest], version_a: str, version_b: str) -> str:
    kinds: dict[str, int] = {}
    for test in tests:
        kinds[test.kind] = kinds.get(test.kind, 0) + 1
    tally = ", ".join(f"{n} {kind}" for kind, n in sorted(kinds.items()))
    slug_a = version_a.replace(".", "-")
    # Wrapped rather than written out, because the two interpolated parts
    # grow: a version string is as long as it likes, and the tally gains a
    # clause per assertion kind in play.
    opening = textwrap.fill(
        f"One test per entry in `pins/pins.jsonl`: each pins a behavior that "
        f"version {version_a} had and version {version_b} does not, at a "
        f"response field some declared customer workflow actually reads. "
        f"{len(tests)} test(s): {tally}.", width=WIDTH)
    body = f"""Pinned-behavior regression tests. {MARKER} — do not edit.

{opening}

Run them against one version at a time. Live, against the API:

    uv run pytest pinned/ --api-version {version_a}
    uv run pytest pinned/ --api-version {version_b}

The first run passes and the second fails; that difference is the whole
claim. Against a recorded replay instead, which needs no key and no network:

    uv run pytest pinned/ --api-version {version_a} \\
        --records corpus/replay-{slug_a}.jsonl

A failure here means one of two things, and they are not the same: an
assertion failure is the pinned behavior gone, while `[unreached]` in the
message means the replay never got as far as the step, so the pin was never
exercised at all. `compatlab pin certify` keeps those apart.
"""
    return f"{TRIPLE}{body}{TRIPLE}\n\n{_imports(set(kinds))}\n"


def render_module(tests: list[PinnedTest], version_a: str, version_b: str) -> str:
    """The whole generated module, deterministic in the order of `tests`.

    Refuses to emit two tests under one name. `pinning.name_for` shortens a
    name that would push `def NAME(` past the line length, and the way it
    shortens — dropping the workflow and keeping the step — can in principle
    collide, because two workflows may share a step name and a locus. Python
    would not complain: the second definition would silently replace the
    first, the suite would quietly lose a pin, and `pin certify` would report
    a smaller number without reporting a problem. A pin that vanishes is the
    one failure this suite must not have.
    """
    seen: dict[str, str] = {}
    for test in tests:
        if test.name in seen:
            raise ValueError(
                f"two pins compile to the test name {test.name!r}: "
                f"{seen[test.name]} and {test.pin.corpus}")
        seen[test.name] = test.pin.corpus
    parts = [_header(tests, version_a, version_b)]
    parts += [render_test(test, version_a, version_b) for test in tests]
    return "\n\n".join(parts)
