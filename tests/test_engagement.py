"""The engagement writeup, as tests.

`docs/engagement.md` is the only hand-written document in this repository that
quotes the generated figures, and it is the one a reader is most likely to
reach first. Every other published artifact is regenerated by a command and
diffed in CI; this one is prose, so the numbers in it are pinned here instead.

A figure that drifts fails the suite rather than aging quietly into a wrong
claim on a portfolio page.
"""

from __future__ import annotations

import json
import pathlib
import re

import pytest

from compatlab import VERSION_A, VERSION_B, baseline, scoring
from compatlab.canonical import canonical_side
from compatlab.cli import _findings_from
from compatlab.differ import diff_pairs, sides
from compatlab.impact import BLOCKS, CORRUPTS, map_findings
from compatlab.pinning import load_pins
from compatlab.verify import verify
from compatlab.workflows import load_all, validate

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAIRS = ROOT / "replay" / "pairs.jsonl"
DOC = ROOT / "docs" / "engagement.md"

pytestmark = pytest.mark.skipif(
    not PAIRS.exists(), reason="no replay output committed")


def doc() -> str:
    return DOC.read_text()


def pairs() -> list[dict]:
    return [json.loads(line) for line in PAIRS.read_text().splitlines() if line]


def card() -> dict:
    index = baseline.BaselineIndex.load(ROOT / "baseline" / "schema-diff-index.jsonl")
    adjudication = scoring.Adjudication.load(ROOT / "scoring" / "adjudication.json")
    records = pairs()
    return scoring.score(diff_pairs(records), index, adjudication, records)


def impact():
    declared = load_all(ROOT / "workflows")
    findings = _findings_from(ROOT / "findings" / "findings.jsonl")
    report = map_findings(declared, findings, version_a=VERSION_A,
                          version_b=VERSION_B)
    side_a, side_b = sides(pairs())
    canon_a, canon_b = canonical_side(side_a), canonical_side(side_b)
    return report, verify(report, pairs(), canon_a, canon_b), declared


def thousands(n: int) -> str:
    return f"{n:,}"


# The writeup is prose, so small counts are spelled out in it.
WORDS = ("zero", "one", "two", "three", "four", "five", "six", "seven",
         "eight", "nine", "ten")


def word(n: int) -> str:
    return WORDS[n] if n < len(WORDS) else str(n)


def test_the_corpus_shape_is_quoted_correctly():
    records = pairs()
    endpoints = len({(r["method"], r["path_template"]) for r in records})
    workflows = len(load_all(ROOT / "workflows"))
    scenarios = len(list((ROOT / "scenarios").glob("*.json")))
    assert f"{len(records)} calls over {endpoints} endpoints" in doc()
    assert f"{word(workflows)} declared integration workflows" in doc()
    assert f"the {word(scenarios)} capture scenarios" in doc()


def test_recall_is_quoted_with_its_denominator_and_the_inventory():
    ground = card()["ground_truth"]
    exercised = sum(1 for b in ground["breaks"] if b["exercised"])
    caught = sum(1 for b in ground["breaks"] if b["exercised"] and b["caught"])
    assert (f"Caught {caught} of the {exercised} documented behavioral breaks "
            f"the corpus exercises" in doc())
    assert f"({ground['m']}\n  in the inventory" in doc()
    # The unexercised half is named as a limitation, not rounded away.
    missing = ground["m"] - exercised
    verb = "is" if missing == 1 else "are"
    assert (f"**{word(missing).capitalize()} of the {word(ground['m'])} documented "
            f"breaks in the inventory {verb} unexercised.**" in doc())


def test_the_baseline_figures_are_quoted_exactly():
    base = card()["baseline"]
    text = doc()
    for key in ("entries_unscoped", "entries_matched_paths",
                "entries_corpus_endpoints"):
        assert thousands(base[key]) in text, key
    top_rule, top_count = max(base["rule_mix"].items(), key=lambda kv: kv[1])
    assert f"{thousands(top_count)} of those" in text
    assert f"`{top_rule}`" in text


def test_the_per_break_baseline_verdicts_match_the_table():
    rows = re.findall(r"^\| (.+?) \| (no entry at all|named the field, not the "
                      r"behavior|reported) \|$", doc(), re.MULTILINE)
    assert rows, "the baseline-verdict table did not parse"
    wording = {"green": "no entry at all",
               "named": "named the field, not the behavior",
               "reported": "reported"}
    caught = [b for b in card()["ground_truth"]["breaks"] if b["caught"]]
    assert len(rows) == len(caught)
    assert [wording[b["baseline"]] for b in caught] == [r[1] for r in rows]


def test_the_finding_counts_and_false_break_verdicts_are_quoted():
    scored = card()
    findings, false_breaks = scored["findings"], scored["false_breaks"]
    text = doc()
    assert (f"**{findings['total']} findings** over "
            f"{findings['steps_with_findings']} of the "
            f"{findings['steps_compared']} steps" in text)
    for severity in ("breaking", "risky", "benign"):
        assert f"{findings['by_severity'][severity]} {severity}" in text
    assert false_breaks["rate"] == 0
    assert "**0 false breaks.**" in text
    counts = false_breaks["verdicts"]
    assert (f"{counts.get('documented', 0)} documented, "
            f"{counts.get('undocumented', 0)} undocumented, "
            f"{counts.get('false-break', 0)} false-break" in text)


def test_every_workflow_verdict_appears_with_its_criticality():
    report, verification, declared = impact()
    text = doc()
    assert f"affects **{len(report.affected)} of the {len(declared)} workflows**" in text
    labelled = {i.workflow.name: "**BLOCKED**" for i in report.by_verdict(BLOCKS)}
    labelled |= {i.workflow.name: "**CORRUPTED**"
                 for i in report.by_verdict(CORRUPTS)}
    for workflow in declared:
        row = f"| `{workflow.name}` | {workflow.criticality} |"
        assert row in text, workflow.name
        if workflow.name in labelled:
            assert f"{row} {labelled[workflow.name]} |" in text, workflow.name
    assert (f"{len(verification.confirmed)} of {len(verification.checks)} claims"
            in text)


def test_the_declared_inventory_still_matches_the_traffic():
    # The writeup leans on the inventory being valid; Phase 4's own gate is
    # what makes that true, so it is asserted here rather than assumed.
    _, _, declared = impact()
    side_a, _ = sides(pairs())
    seqs = {(p["workflow"], p["step"]): p["seq"] for p in pairs()}
    assert validate(declared, canonical_side(side_a), seqs).ok


def test_the_pin_count_is_quoted_with_both_versions():
    count = len(load_pins(ROOT / "pins" / "pins.jsonl"))
    assert (f"**{count} of {count} pass on `{VERSION_A}` and fail on "
            f"`{VERSION_B}`**" in doc())


def test_the_quoted_test_body_is_a_line_from_the_generated_suite():
    suite = (ROOT / "pinned" / "test_pinned_behavior.py").read_text()
    quoted = re.search(r"^    assert value_at\(.+$", doc(), re.MULTILINE)
    assert quoted, "the writeup no longer shows a pinned assertion"
    assert quoted.group(0) in suite


def test_every_relative_link_resolves():
    # A writeup whose deliverable links 404 is worse than one with none.
    for target in re.findall(r"\]\((?!https?:)([^)#]+)", doc()):
        assert (DOC.parent / target).resolve().exists(), target
